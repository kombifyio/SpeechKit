const pairingUsage = `usage: speechkit-server pairing <command> [flags]

LAN device pairing (speechkit.pairing.v2) against the running server.

commands:
  list              open pairing requests and paired devices
  approve <code>    approve the request whose device shows <code>
  deny <code>       refuse that request
  revoke <id>       revoke a paired device (dev_...); its next call is refused

flags:
  --config <path>   config.toml (default $SPEECHKIT_CONFIG_PATH or /etc/speechkit/config.toml)
  --server <url>    server base URL (default http://127.0.0.1:<listen port>)
  --json            print the server's JSON answer

The command authenticates with the server bearer from the configured
bearer_token_env (also the token generated by /setup); run it where the server
runs (remote servers require HTTPS), for example: docker exec speechkit speechkit-server pairing list`

func runPairing(args []string) int {
	if len(args) == 0 || args[0] == "-h" || args[0] == "--help" || args[0] == "help" {
		fmt.Fprintln(os.Stderr, pairingUsage)
		return 2
	}
	command := args[0]
	flags := flag.NewFlagSet("pairing "+command, flag.ContinueOnError)
	configPath := flags.String("config", defaultPairingConfigPath(), "path to config.toml")
	serverURL := flags.String("server", "", "server base URL")
	asJSON := flags.Bool("json", false, "print JSON")
	// Flags may follow the positional argument (approve <code> --config …).
	var positional []string
	rest := args[1:]
	for {
		if err := flags.Parse(rest); err != nil {
			return 2
		}
		rest = flags.Args()
		if len(rest) == 0 {
			break
		}
		positional = append(positional, rest[0])
		rest = rest[1:]
	}

	client, err := newPairingClient(*configPath, *serverURL)
	if err != nil {
		fmt.Fprintln(os.Stderr, "speechkit-server pairing:", err)
		return 2
	}
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()

	switch command {
	case "list":
		return client.list(ctx, *asJSON)
	case "approve", "deny":
		if len(positional) != 1 {
			fmt.Fprintf(os.Stderr, "speechkit-server pairing %s <code>\n", command)
			return 2
		}
		code := pairing.NormalizeCode(positional[0])
		if command == "approve" {
			// Inspect the operator listing before approval so replacement is visible.
			raw, status, err := client.do(ctx, http.MethodGet, "/v1/pairing/device-requests", nil)
			if result := client.report(raw, status, err, false, func([]byte) {}); result != 0 {
				return result
			}
			var listing struct {
				Requests []pairing.DeviceRequest `json:"device_requests"`
			}
			if err := json.Unmarshal(raw, &listing); err != nil {
				fmt.Fprintln(os.Stderr, "speechkit-server pairing: unexpected listing")
				return 1
			}
			for _, req := range listing.Requests {
				if req.Code == code && req.ReplacesDeviceID != "" {
					fmt.Fprintf(os.Stderr, "replacement: approving %s %q replaces paired device %s (self-asserted device_id %s)\n", req.Code, req.Name, req.ReplacesDeviceID, req.HardwareID)
				}
			}
		}
		body, status, err := client.do(ctx, http.MethodPost, "/v1/pairing/device-requests/"+command, map[string]string{"code": code})
		return client.report(body, status, err, *asJSON, func(raw []byte) {
			var out struct {
				Req pairing.DeviceRequest `json:"device_request"`
			}
			_ = json.Unmarshal(raw, &out)
			verb := "approved"
			if command == "deny" {
				verb = "denied"
			}
			fmt.Printf("%s %s %q (%s) from %s; the device collects its token on its next poll\n",
				verb, out.Req.Code, out.Req.Name, out.Req.Kind, out.Req.Source)
		})
	case "revoke":
		if len(positional) != 1 {
			fmt.Fprintln(os.Stderr, "speechkit-server pairing revoke <device id>")
			return 2
		}
		body, status, err := client.do(ctx, http.MethodDelete, "/v1/pairing/devices/"+url.PathEscape(positional[0]), nil)
		return client.report(body, status, err, *asJSON, func(raw []byte) {
			var out struct {
				Dev pairing.Device `json:"revoked"`
			}
			_ = json.Unmarshal(raw, &out)
			fmt.Printf("revoked %s %q; its token is refused from now on\n", out.Dev.ID, out.Dev.Name)
		})
	default:
		fmt.Fprintln(os.Stderr, pairingUsage)
		return 2
	}
}

func defaultPairingConfigPath() string {
	if p := strings.TrimSpace(os.Getenv("SPEECHKIT_CONFIG_PATH")); p != "" {
		return p
	}
	return "/etc/speechkit/config.toml"
}

type pairingClient struct {
	base  string
	token string
	http  *http.Client
}

// newPairingClient resolves the server URL and bearer the same way the server
// does: config.toml, then the /setup settings file, then deployment env.
func newPairingClient(configPath, serverURL string) (*pairingClient, error) {
	cfg, err := config.Load(configPath)
	if err != nil {
		return nil, fmt.Errorf("load config %q: %w", configPath, err)
	}
	config.ApplyServerRuntimeDefaults(cfg)
	if config.KombifyDeploymentDefaultsRequested() {
		config.ApplyKombifyDeploymentDefaults(cfg)
	}
	if _, err := config.ApplyServerModelSettingsFile(cfg); err != nil {
		return nil, fmt.Errorf("load server settings: %w", err)
	}
	if _, err := config.ApplyServerDeploymentEnv(cfg); err != nil {
		return nil, fmt.Errorf("apply deployment env: %w", err)
	}
	base := strings.TrimRight(strings.TrimSpace(serverURL), "/")
	if base == "" {
		port := "8080"
		if _, p, err := net.SplitHostPort(strings.TrimSpace(cfg.Server.ListenAddr)); err == nil && p != "" {
			port = p
		}
		base = "http://127.0.0.1:" + port
	}
	u, err := url.Parse(base)
	if err != nil || u.Hostname() == "" || u.User != nil || (u.Scheme != "http" && u.Scheme != "https") {
		return nil, errors.New("--server must be an absolute HTTP(S) URL without user information")
	}
	ip := net.ParseIP(u.Hostname())
	if u.Scheme == "http" && !(ip != nil && ip.IsLoopback()) && !strings.EqualFold(u.Hostname(), "localhost") {
		return nil, errors.New("--server requires HTTPS for a non-loopback host; refusing to send the server bearer over plain HTTP")
	}
	envName := strings.TrimSpace(cfg.Server.BearerTokenEnv)
	if envName == "" {
		envName = "SPEECHKIT_SERVER_TOKEN"
	}
	token := strings.TrimSpace(os.Getenv(envName))
	if token == "" {
		return nil, fmt.Errorf("no server bearer in $%s; device pairing is managed with the server bearer", envName)
	}
	return &pairingClient{base: base, token: token, http: &http.Client{Timeout: 10 * time.Second, CheckRedirect: func(*http.Request, []*http.Request) error { return http.ErrUseLastResponse }}}, nil
}

func (c *pairingClient) do(ctx context.Context, method, path string, body any) ([]byte, int, error) {
	var reader io.Reader
	if body != nil {
		raw, err := json.Marshal(body)
		if err != nil {
			return nil, 0, err
		}
		reader = bytes.NewReader(raw)
	}
	req, err := http.NewRequestWithContext(ctx, method, c.base+path, reader)
	if err != nil {
		return nil, 0, err
	}
	req.Header.Set("Authorization", "Bearer "+c.token)
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	resp, err := c.http.Do(req)
	if err != nil {
		return nil, 0, err
	}
	defer func() { _ = resp.Body.Close() }()
	raw, err := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	return raw, resp.StatusCode, err
}

func (c *pairingClient) report(body []byte, status int, err error, asJSON bool, human func([]byte)) int {
	if err != nil {
		fmt.Fprintln(os.Stderr, "speechkit-server pairing:", err)
		return 1
	}
	if status < 200 || status > 299 {
		fmt.Fprintf(os.Stderr, "speechkit-server pairing: HTTP %d: %s\n", status, strings.TrimSpace(string(body)))
		return 1
	}
	if asJSON {
		fmt.Println(strings.TrimSpace(string(body)))
		return 0
	}
	human(body)
	return 0
}

func (c *pairingClient) list(ctx context.Context, asJSON bool) int {
	reqBody, reqStatus, reqErr := c.do(ctx, http.MethodGet, "/v1/pairing/device-requests", nil)
	if code := c.report(reqBody, reqStatus, reqErr, false, func([]byte) {}); code != 0 {
		return code
	}
	devBody, devStatus, devErr := c.do(ctx, http.MethodGet, "/v1/pairing/devices", nil)
	if code := c.report(devBody, devStatus, devErr, false, func([]byte) {}); code != 0 {
		return code
	}
	var requests struct {
		Requests []pairing.DeviceRequest `json:"device_requests"`
		Enabled  bool                    `json:"enabled"`
	}
	var devices struct {
		Devices []pairing.Device `json:"devices"`
	}
	if err := errors.Join(json.Unmarshal(reqBody, &requests), json.Unmarshal(devBody, &devices)); err != nil {
		fmt.Fprintln(os.Stderr, "speechkit-server pairing: unexpected answer:", err)
		return 1
	}
	if asJSON {
		raw, _ := json.MarshalIndent(map[string]any{
			"device_requests_enabled": requests.Enabled,
			"device_requests":         requests.Requests,
			"devices":                 devices.Devices,
		}, "", "  ")
		fmt.Println(string(raw))
		return 0
	}
	state := "open"
	if !requests.Enabled {
		state = "closed ([server.pairing] device_requests = false)"
	}
	fmt.Printf("device pairing: %s\n\nopen requests (%d):\n", state, len(requests.Requests))
	tw := tabwriter.NewWriter(os.Stdout, 2, 4, 2, ' ', 0)
	_, _ = fmt.Fprintln(tw, "  CODE\tDEVICE\tKIND\tFROM\tEXPIRES\tREPLACES")
	for _, r := range requests.Requests {
		_, _ = fmt.Fprintf(tw, "  %s\t%s\t%s\t%s\t%s\t%s\n", r.Code, r.Name, r.Kind, r.Source, r.ExpiresAt.Local().Format("15:04:05"), r.ReplacesDeviceID)
	}
	_ = tw.Flush()
	fmt.Printf("\npaired devices (%d):\n", len(devices.Devices))
	_, _ = fmt.Fprintln(tw, "  ID\tDEVICE\tKIND\tPAIRED\tLAST USED")
	for _, d := range devices.Devices {
		last := "-"
		if d.LastUsedAt != nil {
			last = d.LastUsedAt.Local().Format(time.DateTime)
		}
		_, _ = fmt.Fprintf(tw, "  %s\t%s\t%s\t%s\t%s\n", d.ID, d.Name, d.Kind, d.CreatedAt.Local().Format(time.DateTime), last)
	}
	_ = tw.Flush()
	return 0
}
